const BLANK = '.........'
const WISP = ['.#..#..#.', '#..#..#..', '.#..#..#.', '..#..#..#']

// Frames for the running modals: steam rises, the drop fills, flush drops fall.
export const ANIMATIONS: Record<'steam' | 'water' | 'flush', string[][]> = {
  steam: [0, 1, 2, 3].map((f) => [0, 1, 2, 3, 4, 5].map((r) => WISP[(r + f) % 4]).concat([BLANK, '#########', BLANK])),
  water: [[], [7], [6, 7], [4, 5, 6, 7]].map((filled) =>
    GLYPHS.water.map((line, r) => (filled.includes(r) ? line.replace(/#(\.+)#/, (_, inner: string) => `#${'#'.repeat(inner.length)}#`) : line)),
  ),
  flush: [0, 1, 2, 3].map((f) =>
    ['..#####..', '.#######.', BLANK].concat([3, 4, 5, 6, 7, 8].map((r) => {
      const d = (r - 3 - f + 8) % 4
      return d === 0 ? '.#.#.#.#.' : d === 2 ? '#.#.#.#.#' : BLANK
    })),
  ),
}

export function litDots(rows: readonly string[]): { c: number; r: number }[] {
  const dots: { c: number; r: number }[] = []
  rows.forEach((line, r) => line.split('').forEach((ch, c) => ch === '#' && dots.push({ c, r })))
  return dots
}
